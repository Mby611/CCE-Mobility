from __future__ import annotations

from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class BenchmarkName(str, Enum):
    TRAVEL_PLANNER = "travelplanner"
    TRAVEL_BENCH = "travelbench"
    MOBILITY_BENCH = "mobilitybench"


class RunMode(str, Enum):
    FACTUAL = "factual"
    COUNTERFACTUAL = "counterfactual"


class RecoveryStrategy(str, Enum):
    PROACTIVE_ADAPT = "proactive_adapt"
    PARTIAL_ADAPT = "partial_adapt"
    PASSIVE_NOTIFY = "passive_notify"
    IGNORE = "ignore"
    HALLUCINATE = "hallucinate"
    BASELINE = "baseline"


class TaskSample(BaseModel):
    """Normalized benchmark sample used by all adapters."""

    sample_id: str
    benchmark: BenchmarkName
    query: str
    context: dict[str, Any] = Field(default_factory=dict)
    ground_truth: dict[str, Any] = Field(default_factory=dict)
    metadata: dict[str, Any] = Field(default_factory=dict)


class ToolEvent(BaseModel):
    """One agent-environment interaction event."""

    step: int
    tool_name: str = ""
    parameters: dict[str, Any] = Field(default_factory=dict)
    observation: str = ""
    action_text: str = ""
    success: bool = True
    metadata: dict[str, Any] = Field(default_factory=dict)


class AgentTrajectory(BaseModel):
    sample_id: str
    run_mode: RunMode
    events: list[ToolEvent] = Field(default_factory=list)
    final_response: str = ""
    raw: dict[str, Any] = Field(default_factory=dict)


class AgentVisibleHistoryEvent(BaseModel):
    """Auditable event fields that were visible to the acting agent."""

    model_config = ConfigDict(extra="forbid")

    step: int
    tool_name: str = ""
    parameters: dict[str, Any] = Field(default_factory=dict)
    observation: str = ""
    action_text: str = ""
    success: bool = True


class FactualRecoveryContext(BaseModel):
    """Frozen factual prefix from which a counterfactual recovery continues.

    The schema deliberately excludes trajectory ``raw`` data and event metadata,
    which may contain intervention, recovery-spec, or evaluator-side fields.
    """

    model_config = ConfigDict(extra="forbid")

    schema_version: Literal["factual-recovery-context-v1"] = "factual-recovery-context-v1"
    sample_id: str
    goal: str
    factual_plan: str = ""
    tool_history: list[AgentVisibleHistoryEvent] = Field(default_factory=list)
    prefix_hash: str


class FactualContextArtifact(BaseModel):
    """Reusable factual trajectory and its agent-visible recovery prefix."""

    model_config = ConfigDict(extra="forbid")

    schema_version: Literal["factual-context-artifact-v1"] = "factual-context-artifact-v1"
    iteration: int = Field(ge=1)
    sample_id: str
    goal: str
    factual: AgentTrajectory
    recovery_context: FactualRecoveryContext
    prefix_hash: str
    artifact_hash: str


class VulnerabilityPoint(BaseModel):
    """A point where a local counterfactual intervention may be informative."""

    sample_id: str
    step: int
    reason: str
    target: Literal["observation", "state", "tool_result", "user_goal", "constraint"] = "state"
    evidence: str = ""
    score: float = 0.0
    metadata: dict[str, Any] = Field(default_factory=dict)


class InterventionSpec(BaseModel):
    """A local counterfactual intervention generated by a world model."""

    intervention_id: str
    sample_id: str
    benchmark: BenchmarkName
    dimension: str
    domain: str = ""
    domain_operator: str = ""
    capability_targets: list[str] = Field(default_factory=list)
    intervention_type: str
    severity: float = 1.0
    trigger_step: int | None = None
    trigger_condition: str = ""
    target_selector: str = ""
    target_entity: dict[str, Any] = Field(default_factory=dict)
    params: dict[str, Any] = Field(default_factory=dict)
    condition_text: str = ""
    diagnostic_goal: str = ""
    expected_recovery_actions: list[str] = Field(default_factory=list)
    validity_constraints: list[str] = Field(default_factory=list)
    is_negative: bool = False
    source: str = "rule"
    metadata: dict[str, Any] = Field(default_factory=dict)


class ExpectedRecoverySpec(BaseModel):
    """Structured ground truth for judging recovery after an intervention."""

    intervention_id: str
    sample_id: str
    capability_targets: list[str] = Field(default_factory=list)
    failure_types: list[str] = Field(default_factory=list)
    recovery_contract: dict[str, Any] = Field(default_factory=dict)
    summary: str
    changed_facts: list[str] = Field(default_factory=list)
    must_detect: list[str] = Field(default_factory=list)
    must_do: list[str] = Field(default_factory=list)
    must_not_do: list[str] = Field(default_factory=list)
    acceptable_recoveries: list[str] = Field(default_factory=list)
    invalid_failures: list[str] = Field(default_factory=list)
    rubric: dict[str, str] = Field(default_factory=dict)
    metadata: dict[str, Any] = Field(default_factory=dict)


class WMPredictionSpec(BaseModel):
    """World-model prediction about how an agent may respond to an intervention."""

    intervention_id: str
    sample_id: str
    predicted_failure_modes: list[str] = Field(default_factory=list)
    predicted_recovery_score_bin: Literal["low", "medium", "high"] = "medium"
    affected_capabilities: list[str] = Field(default_factory=list)
    confidence: float = 0.5
    rationale: str = ""
    source: str = "heuristic_predictive_critic"
    metadata: dict[str, Any] = Field(default_factory=dict)


class InterventionCandidate(BaseModel):
    spec: InterventionSpec
    recovery_spec: ExpectedRecoverySpec | None = None
    validity_score: float = 0.0
    estimated_pass_rate: float | None = None
    diagnosticity: float | None = None
    utility: float | None = None
    validation_notes: list[str] = Field(default_factory=list)


class JudgeScore(BaseModel):
    sample_id: str
    intervention_id: str | None = None
    total: float = 0.0
    detection: float = 0.0
    diagnosis: float = 0.0
    replanning: float = 0.0
    verification: float = 0.0
    communication: float = 0.0
    recovery: float = 0.0
    safety: float = 0.0
    strategy: RecoveryStrategy = RecoveryStrategy.IGNORE
    rationale: str = ""
    raw: dict[str, Any] = Field(default_factory=dict)


class EvaluationRecord(BaseModel):
    sample: TaskSample
    factual: AgentTrajectory | None = None
    counterfactual: AgentTrajectory | None = None
    intervention: InterventionSpec | None = None
    recovery_spec: ExpectedRecoverySpec | None = None
    wm_prediction: WMPredictionSpec | None = None
    factual_score: JudgeScore | None = None
    counterfactual_score: JudgeScore | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)


class ExperimentReport(BaseModel):
    experiment_name: str
    benchmark: str
    method: str
    total_samples: int
    metrics: dict[str, Any] = Field(default_factory=dict)
    records_path: str | None = None
